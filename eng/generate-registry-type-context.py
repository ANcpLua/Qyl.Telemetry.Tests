#!/usr/bin/env python3
"""Project ambiguous wire-key types from the pinned SemanticConventions registry."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess


def semantic(value):
    # Same path-independent fingerprint as SemanticConventions/scripts/generate.sh.
    if isinstance(value, dict):
        result = {}
        for key, item in value.items():
            if key == "provenance":
                item = {
                    field: data
                    for field, data in item.items()
                    if field != "path" or data.startswith(("https://", "http://"))
                }
            result[key] = semantic(item)
        return result
    if isinstance(value, list):
        return [semantic(item) for item in value]
    return value


def value_kind(attribute_type):
    # Same primitive/template projection as kindof in the C# Weaver target.
    if isinstance(attribute_type, dict):
        members = attribute_type.get("members", [])
        first = members[0].get("value") if members else None
        return ("Integer" if type(first) in (int, float) else "String", False)
    if not isinstance(attribute_type, str):
        return ("Unknown", False)
    template = attribute_type.startswith("template[")
    primitive = attribute_type[9:-1] if template else attribute_type
    kinds = {
        "string": "String",
        "int": "Integer",
        "double": "Double",
        "boolean": "Boolean",
        "string[]": "StringArray",
        "int[]": "IntegerArray",
        "double[]": "DoubleArray",
        "boolean[]": "BooleanArray",
        "any": "Any",
    }
    return (kinds.get(primitive, "Unknown"), template)


def generate(semconv):
    snapshot_path = semconv / ".build/registry.json"
    snapshot = json.loads(snapshot_path.read_text(encoding="utf-8"))
    canonical = json.dumps(semantic(snapshot), sort_keys=True, separators=(",", ":"))
    fingerprint = hashlib.sha256(canonical.encode()).hexdigest()
    # Reuse the owning generator's literal-wire-key and collision transformation.
    projected = subprocess.run(
        [
            "jq", "-L", str(semconv / "templates/registry/csharp/jq"),
            'include "symbols"; with_wire_keys | '
            '{attributes: [.registry.attributes[], .dependencies[].registry.attributes[]] '
            '| map({key, type}), contextual: [.context_dependent_attributes[] | {key, type}]}',
            str(snapshot_path),
        ],
        check=True, capture_output=True, text=True,
    )
    facts = json.loads(projected.stdout)
    canonical_kinds = {}
    for attribute in facts["attributes"]:
        canonical_kinds.setdefault(attribute["key"], value_kind(attribute["type"]))
    ambiguous = sorted({
        attribute["key"]
        for attribute in facts["contextual"]
        if value_kind(attribute["type"]) != canonical_kinds[attribute["key"]]
    })
    expression = "\n        or ".join(json.dumps(key) for key in ambiguous)
    expression = f"key is\n        {expression}" if ambiguous else "false"
    return f"""// <auto-generated/>
// Context-dependent wire types from the pinned SemanticConventions resolved registry.
// Regenerate with python3 eng/generate-registry-type-context.py; do not edit by hand.
// </auto-generated>

namespace Qyl.Telemetry.Tests;

internal static class RegistryTypeContext
{{
    internal const string RegistrySha256 = "{fingerprint}";

    internal static bool RequiresDefinition(string key) => {expression};
}}
"""


def main():
    repository = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("semconv", nargs="?", type=Path,
                        default=repository.parent / "Qyl.Telemetry.SemanticConventions")
    parser.add_argument("--check", action="store_true", help="verify the committed projection")
    args = parser.parse_args()
    result = generate(args.semconv.resolve())
    output = repository / "Qyl.Telemetry.Tests/Generated/RegistryTypeContext.g.cs"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != result:
            raise SystemExit(f"Registry type context is stale: regenerate {output}")
        print("Registry type context matches the resolved registry.")
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(result, encoding="utf-8")
    print(f"Generated {output}")


if __name__ == "__main__":
    main()
